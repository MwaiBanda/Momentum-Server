package db

import (
	"context"
	"embed"
	"fmt"
	"io/fs"
	"log"
	"time"

	"github.com/jmoiron/sqlx"
	"github.com/pressly/goose/v3"
)

const baselineVersion int64 = 1
const migrationLockQuery = `SELECT pg_advisory_lock(hashtext('momentum-server-goose-migrations'))`
const migrationUnlockQuery = `SELECT pg_advisory_unlock(hashtext('momentum-server-goose-migrations'))`

//go:embed migrations/*.sql
var migrationFiles embed.FS

func Migrate(ctx context.Context, database *sqlx.DB) error {
	if database == nil {
		return fmt.Errorf("database is required")
	}

	migrations, err := fs.Sub(migrationFiles, "migrations")
	if err != nil {
		return fmt.Errorf("load migrations: %w", err)
	}

	provider, err := goose.NewProvider(goose.DialectPostgres, database.DB, migrations)
	if err != nil {
		return fmt.Errorf("create migration provider: %w", err)
	}

	migrationConnection, err := database.Connx(ctx)
	if err != nil {
		return fmt.Errorf("acquire migration connection: %w", err)
	}
	defer migrationConnection.Close()

	if _, err := migrationConnection.ExecContext(ctx, migrationLockQuery); err != nil {
		return fmt.Errorf("lock database migrations: %w", err)
	}
	defer func() {
		unlockContext, cancel := context.WithTimeout(context.Background(), 5*time.Second)
		defer cancel()

		if _, err := migrationConnection.ExecContext(unlockContext, migrationUnlockQuery); err != nil {
			log.Printf("unlock database migrations: %v", err)
		}
	}()

	if err := ensureGooseVersionTable(ctx, database); err != nil {
		return fmt.Errorf("initialize Goose version table: %w", err)
	}

	if _, err := provider.Up(ctx); err != nil {
		return fmt.Errorf("run database migrations: %w", err)
	}

	return nil
}

func ensureGooseVersionTable(ctx context.Context, database *sqlx.DB) error {
	if _, err := database.ExecContext(ctx, `
		CREATE TABLE IF NOT EXISTS goose_db_version (
			id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
			version_id bigint NOT NULL,
			is_applied boolean NOT NULL,
			tstamp timestamp NOT NULL DEFAULT now()
		)
	`); err != nil {
		return err
	}

	if _, err := database.ExecContext(ctx, `
		INSERT INTO goose_db_version (version_id, is_applied)
		SELECT 0, false
		WHERE NOT EXISTS (
			SELECT 1
			FROM goose_db_version
		)
	`); err != nil {
		return err
	}

	return nil
}

func AdoptBaseline(ctx context.Context, database *sqlx.DB) error {
	if database == nil {
		return fmt.Errorf("database is required")
	}

	tx, err := database.BeginTxx(ctx, nil)
	if err != nil {
		return fmt.Errorf("begin baseline adoption: %w", err)
	}
	defer func() {
		_ = tx.Rollback()
	}()

	if _, err := tx.ExecContext(ctx, `
		CREATE TABLE IF NOT EXISTS goose_db_version (
			id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
			version_id bigint NOT NULL,
			is_applied boolean NOT NULL,
			tstamp timestamp NOT NULL DEFAULT now()
		)
	`); err != nil {
		return fmt.Errorf("create Goose version table: %w", err)
	}

	if _, err := tx.ExecContext(ctx, `
		INSERT INTO goose_db_version (version_id, is_applied)
		SELECT $1, true
		WHERE NOT EXISTS (
			SELECT 1
			FROM goose_db_version
			WHERE version_id = $1 AND is_applied = true
		)
	`, baselineVersion); err != nil {
		return fmt.Errorf("record baseline version: %w", err)
	}

	if err := tx.Commit(); err != nil {
		return fmt.Errorf("commit baseline adoption: %w", err)
	}

	return nil
}
